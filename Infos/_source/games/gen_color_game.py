"""Builds game 6 « De toutes les couleurs » : Infos/Literature/Color_Game.html + color_data.js, and nothing else.
Run:  python3 gen_color_game.py   then   python3 ../../../assets/theme_apply.py Infos/Literature/Color_Game.html
(gen_games.py also calls build() so a full games rebuild keeps this page.)
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
INFOS = HERE.parent.parent
sys.path.insert(0, str(INFOS / 'Vine_and_Vineyard' / '_source'))
from common import base_css  # noqa: E402
import color_bank  # noqa: E402


def build():
    B = color_bank.bank()
    rows = [[b['id'], b['name'].replace("'", '’'), b['lv'], list(b['region']), b['req'], b['opt'], list(b['note']) if b['note'] else None, b['href']] for b in B]
    out = INFOS / 'Literature'
    (out / 'color_data.js').write_text('/* GENERATED by Infos/_source/games/gen_color_game.py from color_bank.py — do not edit by hand. */\n'
                                       'window.COLOR_DATA = ' + json.dumps({'q': rows}, ensure_ascii=False, separators=(',', ':')) + ';\n')
    html = (HERE / 'color_template.html').read_text().replace('@@BASE_CSS@@', base_css()).replace('@@NA@@', str(len(B)))
    assert '@@' not in html
    (out / 'Color_Game.html').write_text(html)
    return len(B)


if __name__ == '__main__':
    print(build(), 'AOCs')
