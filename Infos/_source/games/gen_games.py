def quiz_js():
    Q = quiz_bank.bank()
    links = sorted({q['href'] for q in Q})
    lks = sorted({q['lk'] for q in Q})
    li, ki = {h: i for i, h in enumerate(links)}, {k: i for i, k in enumerate(lks)}
    rows = [[q['id'], q['lv'], q['cat'], list(q['q']), list(q['a']), [list(d) for d in q['d']], list(q['x']),
             li[q['href']], ki[q['lk']]] for q in Q]
