def map_count():
    js = OUTDIR / 'map_game_data.js'
    return js.read_text().count('"card":') if js.exists() else 317


def main():
    OUTDIR.mkdir(exist_ok=True)
    js, n = quiz_js()
    (OUTDIR / 'quiz_data.js').write_text(js)
    tjs, nt = taste_js()
    (OUTDIR / 'taste_data.js').write_text(tjs)
    cjs, nc = cep_js()
    (OUTDIR / 'cep_data.js').write_text(cjs)
    ijs, ni = igp_js()
    (OUTDIR / 'igp_data.js').write_text(ijs)
    fmt = lambda v: f'{v:,}'.replace(',', '\u202f')  # noqa: E731
    for tpl, out in (('quiz_template.html', 'Wine_Quiz.html'), ('hub_template.html', 'Jeux.html'), ('taste_template.html', 'Taste_Quiz.html'),
                     ('cep_template.html', 'Bon_Cep.html'), ('igp_template.html', 'IGP_Game.html')):
        html = (HERE / tpl).read_text().replace('@@BASE_CSS@@', base_css()).replace('@@NQ@@', str(n)).replace('@@NT@@', str(nt)).replace('@@NM@@', str(map_count()))
        html = html.replace('@@NC@@', fmt(nc)).replace('@@NA@@', str(len(cep_bank.AOCS))).replace('@@NI@@', str(ni))
        assert '@@' not in html, html[html.index('@@'):html.index('@@') + 40]
        (OUTDIR / out).write_text(html)
    print(f'quiz_data.js: {len(js) // 1024} KB, {n} questions; taste_data.js: {nt} notes; cep_data.js: {len(cjs) // 1024} KB, {nc} questions; igp_data.js: {ni} questions; pages written')


if __name__ == '__main__':
    main()
