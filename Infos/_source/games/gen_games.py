def taste_js():
    region = {a['name']: a['region'] for a in quiz_bank.AOCS}
    notes = []
    for n in TN.notes():
        notes.append(dict(id=n['id'], aoc=n['aoc'], alias=n['alias'], zone=n['zone'], zonename=n.get('area') or TN.ZONES[n['zone']],
                          label=LABEL.get(n['id'], n['aoc']), region=region[n['aoc']], col=n['col'], grapes=n['grapes'],
                          fr=n['fr'], en=n['en'], why=n['why'], href=quiz_bank.cep_link(n['aoc'])))
    regs = sorted({x['region'] for x in notes})
    data = dict(notes=notes, aocs=[[a['name'], a['region'], a['region']] for a in quiz_bank.AOCS],
                aoczone=TN.AOC_ZONE, regions=regs, regions_en=[REGION_EN.get(r, r) for r in regs])
    return ('/* GENERATED by Infos/_source/games/gen_games.py — do not edit by hand. */\n'
            'window.TASTE_DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'), len(notes)


