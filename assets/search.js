  function dictate(btn, input, onText, onEnd) {
    if (!SR) return null;
    var rec = null;
    btn.hidden = false;
    btn.title = T('Dicter la recherche', 'Dictate your search');
    btn.setAttribute('aria-label', btn.title);
    btn.addEventListener('click', function (e) {
      e.preventDefault(); e.stopPropagation();
      if (rec) { rec.stop(); return; }
      rec = new SR();
      rec.lang = lang() === 'en' ? 'en-GB' : 'fr-FR';
      rec.interimResults = true; rec.maxAlternatives = 1; rec.continuous = false;
      var finalText = '';
      rec.onresult = function (ev) {
        var s = '';
        for (var i = 0; i < ev.results.length; i++) s += ev.results[i][0].transcript;
        s = s.replace(/[.?!]+$/, '').trim();
        input.value = s; onText(s);
        if (ev.results[ev.results.length - 1].isFinal) finalText = s;
      };
      rec.onerror = function (ev) {
        if (ev.error === 'not-allowed' || ev.error === 'service-not-allowed')
          onEnd(T('Le micro n’est pas autorisé pour ce site (réglages du navigateur).', 'The microphone is not allowed for this site (browser settings).'));
        else if (ev.error === 'no-speech') onEnd(T('Je n’ai rien entendu — réessayez.', 'I didn’t hear anything — try again.'));
        else if (ev.error !== 'aborted') onEnd(T('Dictée indisponible', 'Dictation unavailable') + ' (' + ev.error + ')');
      };
      rec.onend = function () { btn.classList.remove('on'); rec = null; if (finalText) onEnd(null, finalText); input.focus(); };
      try { rec.start(); btn.classList.add('on'); onEnd(T('Parlez… (ex. « Pommard », « taille Guyot »)', 'Speak… (e.g. “Pommard”, “Guyot pruning”)')); }
      catch (err) { rec = null; }
    });
    return { stop: function () { if (rec) rec.abort(); } };
  }

