/* French Wine — site-wide cream / dark theme toggle.
   Loaded synchronously in <head> so the saved theme applies before first paint.
   Page-specific colours live in each page's <style id="fw-theme-css"> (generated by theme_apply.py). */
(function () {
  if (window.__fwTheme) return; window.__fwTheme = true;
  var DEFAULT = 'cream';                 // theme used on a first visit
  var KEY = 'fw_theme';
  var root = document.documentElement;

  var t = DEFAULT;
  try {
    var s = localStorage.getItem(KEY) || localStorage.getItem('fw_cep_theme');
    if (s === 'cream' || s === 'dark') t = s;
  } catch (e) {}
  root.setAttribute('data-theme', t);

  // Language memory. Every page reads the FR/EN choice from localStorage fw_lang; it is also kept in a
  // 1-year cookie, shared by vinopedia.wine, www. and http/https (localStorage is not), so the choice
  // follows the visitor whatever address they use. Runs before any page script reads fw_lang.
  (function () {
    function cookie() { var m = document.cookie.match(/(?:^|;\s*)fw_lang=(en|fr)\b/); return m ? m[1] : ''; }
    function write(l) {
      if (l !== 'en' && l !== 'fr') return;
      var dom = /(^|\.)vinopedia\.wine$/i.test(location.hostname) ? '; domain=vinopedia.wine' : '';
      try { document.cookie = 'fw_lang=' + l + '; max-age=31536000; path=/; SameSite=Lax' + dom; } catch (e) {}
    }
    function local() { try { var s = localStorage.getItem('fw_lang'); return s === 'en' || s === 'fr' ? s : ''; } catch (e) { return ''; } }
    var s = local(), c = cookie();
    if (!s && c) { try { localStorage.setItem('fw_lang', c); } catch (e) {} }
    else if (s && s !== c) write(s);
    // pages with their own FR/EN button only write localStorage: copy the latest choice to the cookie on leaving
    function flush() { var l = local(); if (l && l !== cookie()) write(l); }
    window.addEventListener('pagehide', flush);
    document.addEventListener('visibilitychange', function () { if (document.visibilityState === 'hidden') flush(); });
    window.fwLangCookie = { get: cookie, set: write };
  })();

  function lang() {
    var l = '';
    try { l = localStorage.getItem('fw_lang') || ''; } catch (e) {}
    if (!l && window.fwLangCookie) l = window.fwLangCookie.get();
    return (l || root.lang || 'fr').slice(0, 2) === 'en' ? 'en' : 'fr';
  }
  function label() {
    var cream = root.getAttribute('data-theme') === 'cream';
    return lang() === 'en' ? (cream ? 'Dark' : 'Cream') : (cream ? 'Fond sombre' : 'Fond crème');
  }
  function set(theme) {
    root.setAttribute('data-theme', theme);
    try { localStorage.setItem(KEY, theme); } catch (e) {}
    refresh();
  }
  function toggle() { set(root.getAttribute('data-theme') === 'cream' ? 'dark' : 'cream'); }

  var ICON = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><circle cx="12" cy="12" r="8.5"/><path d="M12 3.5v17A8.5 8.5 0 0 0 12 3.5Z" fill="currentColor"/></svg>';
  var btn = null;
  function refresh() {
    if (!btn) return;
    var sp = btn.querySelector('.fw-tl'); if (sp) sp.textContent = label();
    btn.setAttribute('aria-pressed', root.getAttribute('data-theme') === 'dark' ? 'true' : 'false');
  }

  var CSS =
    '.fw-theme-btn{display:inline-flex;align-items:center;gap:8px;cursor:pointer;font:600 11px/1 ui-sans-serif,system-ui,-apple-system,"Segoe UI",Arial,sans-serif;' +
    'letter-spacing:.16em;text-transform:uppercase;border-radius:999px;padding:8px 16px;transition:background .2s,border-color .2s,color .2s;' +
    'color:#e7cf9c;border:1px solid rgba(217,179,107,.35);background:rgba(24,5,11,.55);-webkit-backdrop-filter:blur(10px);backdrop-filter:blur(10px);}' +
    '.fw-theme-btn:hover{border-color:rgba(217,179,107,.7);}' +
    '.fw-theme-btn svg{width:15px;height:15px;flex:none;}' +
    'html[data-theme="cream"] .fw-theme-btn{color:#8e1f33;border-color:rgba(142,31,51,.3);background:rgba(255,253,248,.9);}' +
    'html[data-theme="cream"] .fw-theme-btn:hover{border-color:rgba(142,31,51,.6);}' +
    '.fw-theme-btn.fw-float{position:fixed;top:14px;right:14px;z-index:100000;box-shadow:0 6px 18px rgba(0,0,0,.18);}' +
    '@media (max-width:560px){.fw-theme-btn.fw-float{top:auto;bottom:14px;right:14px;} .fw-theme-btn .fw-tl{display:none;} .fw-theme-btn{padding:9px;}}' +
    '@media print{.fw-theme-btn{display:none!important;}}';

  function mount() {
    // follow the page's FR/EN switch
    new MutationObserver(refresh).observe(root, { attributes: true, attributeFilter: ['lang'] });
    // A page that already has its own theme button (Cépages & Appellations) keeps it.
    var own = document.getElementById('themebtn');
    if (own) {
      btn = own;
      if (!own.querySelector('.fw-tl')) { var l = document.getElementById('themelbl'); if (l) l.classList.add('fw-tl'); }
      own.addEventListener('click', function (e) { e.stopImmediatePropagation(); toggle(); }, true);
      refresh(); ready(); return;
    }
    var st = document.createElement('style'); st.textContent = CSS; document.head.appendChild(st);
    btn = document.createElement('button');
    btn.type = 'button'; btn.className = 'fw-theme-btn';
    btn.setAttribute('aria-label', 'Theme');
    btn.innerHTML = ICON + '<span class="fw-tl"></span>';
    btn.addEventListener('click', toggle);
    var langBtn = document.querySelector('.topbar .lang, .topbar #langbtn');
    if (langBtn && langBtn.parentNode) {
      // keep the pair together at the right of a space-between top bar
      var grp = document.createElement('span');
      grp.style.cssText = 'display:inline-flex;align-items:center;gap:8px;flex-wrap:wrap;justify-content:flex-end;';
      langBtn.parentNode.insertBefore(grp, langBtn);
      grp.appendChild(btn); grp.appendChild(langBtn);
    }
    else { btn.classList.add('fw-float'); document.body.appendChild(btn); }
    refresh(); ready();
  }
  // nav.js waits for this so it can move the button into the map toolbar / dock
  function ready() {
    window.__fwThemeMounted = true;
    try { document.dispatchEvent(new CustomEvent('fw:theme-mounted')); } catch (e) {}
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', mount); else mount();

  // ---- smooth map zoom (same feel as the « Placez l'AOC » game) on every Leaflet map.
  // Leaflet is not loaded yet: catch the moment it sets window.L, then hook every new map.
  // While the wheel turns, the drawn map is only CSS-scaled (map._move, cursor point fixed, ~60 fps);
  // everything is redrawn sharp once the gesture stops. +/- buttons use the same easing.
  (function () {
    var Lv, hooked = false;
    function hook(L) {
      if (hooked || !L || !L.Map || !L.Map.addInitHook || !L.DomEvent) return;
      hooked = true;
      L.Map.addInitHook(function () { try { smooth(this, L); } catch (e) {} });
      L.Map.addInitHook(function () { try { clearFly(this); } catch (e) {} });
    }
    try {
      Object.defineProperty(window, 'L', { configurable: true, enumerable: true,
        get: function () { if (!hooked) hook(Lv); return Lv; },
        set: function (v) { Lv = v; hook(v); } });
    } catch (e) {}

    // ---- « fly to an appellation » lands in the map area left clear by the cards floating over it
    // (title card, legend, info card, pinned tooltip…): each visible overlay trims the side of the free
    // rectangle that keeps the most room; overlays are skipped once the free area would get too small.
    // Measured one tick later, so an info card opened right after the call is taken into account.
    function clearFly(m) {
      if (m.options.dragging === false) return;
      var fly = m.flyToBounds;
      m.flyToBounds = function (bounds, opts) {
        var self = this, o = {}, k; opts = opts || {};
        for (k in opts) o[k] = opts[k];
        setTimeout(function () {
          try { var p = freePad(self); if (p) { delete o.padding; o.paddingTopLeft = p[0]; o.paddingBottomRight = p[1]; } } catch (e) {}
          fly.call(self, bounds, o);
        }, 0);
        return this;
      };
    }
    function freePad(m) {
      var box = m.getContainer(), mr = box.getBoundingClientRect();
      if (!mr.width || !mr.height) return null;
      var MIN = 110, f = { l: mr.left + 24, t: mr.top + 24, r: mr.right - 24, b: mr.bottom - 24 }, obs = [];
      var scope = box.parentElement && box.parentElement.parentElement || document.body;
      Array.prototype.forEach.call(scope.querySelectorAll('*'), function (el) {
        if (el === box || box.contains(el) || el.contains(box)) return;
        var cs = getComputedStyle(el);
        if (cs.position !== 'absolute' && cs.position !== 'fixed') return;
        if (cs.display === 'none' || cs.visibility === 'hidden' || +cs.opacity === 0) return;
        if (el.parentElement && el.parentElement !== scope && getComputedStyle(el.parentElement).position !== 'static' &&
            el.parentElement !== box.parentElement) return;                       // only top-level floating cards
        var r = el.getBoundingClientRect();
        var x0 = Math.max(r.left, mr.left), x1 = Math.min(r.right, mr.right), y0 = Math.max(r.top, mr.top), y1 = Math.min(r.bottom, mr.bottom);
        if (x1 - x0 < 24 || y1 - y0 < 16 || (x1 - x0) * (y1 - y0) < 2500) return;
        obs.push({ l: x0 - 12, t: y0 - 12, r: x1 + 12, b: y1 + 12, a: (x1 - x0) * (y1 - y0) });
      });
      obs.sort(function (a, b) { return b.a - a.a; });
      obs.forEach(function (o) {
        if (o.r <= f.l || o.l >= f.r || o.b <= f.t || o.t >= f.b) return;      // already outside the free area
        var c = [{ l: Math.max(f.l, o.r), t: f.t, r: f.r, b: f.b }, { l: f.l, t: f.t, r: Math.min(f.r, o.l), b: f.b },
                 { l: f.l, t: Math.max(f.t, o.b), r: f.r, b: f.b }, { l: f.l, t: f.t, r: f.r, b: Math.min(f.b, o.t) }];
        var best = null, ba = 0;
        c.forEach(function (q) { var w = q.r - q.l, h = q.b - q.t; if (w >= MIN && h >= MIN && w * h > ba) { ba = w * h; best = q; } });
        if (best) f = best;
      });
      return [[f.l - mr.left, f.t - mr.top], [mr.right - f.r, mr.bottom - f.b]];
    }

    function smooth(m, L) {
      if (m.options.dragging === false) return;            // helper maps (magnifier lens, insets)
      (window.__fwMaps = window.__fwMaps || []).push(m);
      var box = m.getContainer(), goal, moving = false, raf = 0, endT = 0, mouse, startLL, centerPt;
      function step() {
        var z = m.getZoom(), nz = z + (goal - z) * 0.22;
        if (Math.abs(goal - nz) < 0.002) nz = goal;
        var c = m.unproject(m.project(startLL, nz).subtract(mouse.subtract(centerPt)), nz);
        m._move(c, nz);
        raf = nz !== goal ? requestAnimationFrame(step) : 0;
      }
      function finish() {
        if (raf) { endT = setTimeout(finish, 60); return; }
        moving = false; m._moveEnd(true); m.fire('smoothzoomend');
        var snap = m.options.zoomSnap;                       // maps that want whole zoom levels
        if (snap) { var z = m.getZoom(), s = Math.round(z / snap) * snap; if (Math.abs(s - z) > 1e-3) m.setZoomAround(mouse, s); }
      }
      function kick(d, pt) {
        if (!m.getSize().x || !m.getSize().y) return;          // map not laid out yet (hidden tab / 0-size)
        mouse = pt; centerPt = m.getSize()._divideBy(2);
        if (!moving) { m.stop(); moving = true; goal = m.getZoom(); m._moveStart(true, false); m.fire('smoothzoomstart'); }
        startLL = m.containerPointToLatLng(mouse);
        goal = Math.max(m.getMinZoom(), Math.min(m.getMaxZoom(), goal + d));
        if (!raf) raf = requestAnimationFrame(step);
        clearTimeout(endT); endT = setTimeout(finish, 180);
      }
      // capture phase: runs before (and replaces) any page-level wheel handler on the map
      box.addEventListener('wheel', function (e) {
        var t = e.target;
        if (t && t.closest && t.closest('.leaflet-control,.leaflet-popup')) return;   // scrollable legends, popups
        e.preventDefault(); e.stopImmediatePropagation();
        kick(L.DomEvent.getWheelDelta(e) * (e.ctrlKey ? 0.12 : 0.045), m.mouseEventToContainerPoint(e));
      }, { capture: true, passive: false });
      // +/- buttons (and any page code calling zoomIn/zoomOut) ease the same way, around the centre
      function zin(d) { kick(+(d || m.options.zoomDelta || 1), m.getSize()._divideBy(2)); return m; }
      function zout(d) { kick(-(d || m.options.zoomDelta || 1), m.getSize()._divideBy(2)); return m; }
      try {
        Object.defineProperty(m, 'zoomIn', { configurable: true, get: function () { return zin; }, set: function () {} });
        Object.defineProperty(m, 'zoomOut', { configurable: true, get: function () { return zout; }, set: function () {} });
      } catch (e) {}
    }
  })();

  // site-wide menu + FR/EN switch (assets/nav.js, generated by nav_build.py)
  var me = document.currentScript && document.currentScript.src;
  if (me) { var ns = document.createElement('script'); ns.src = me.replace(/theme\.js(\?.*)?$/, 'nav.js'); document.head.appendChild(ns); }

  // free member access (assets/access.js): set visitor / member state before first paint, then load the popup + locks
  try { root.classList.add(localStorage.getItem('fw_member') ? 'fw-member' : 'fw-guest'); } catch (e) { root.classList.add('fw-guest'); }
  if (me) { var as = document.createElement('script'); as.src = me.replace(/theme\.js(\?.*)?$/, 'access.js'); document.head.appendChild(as); }

  // © 2026 Christophe A. Paul notice (assets/copyright.js)
  if (me) { var cs = document.createElement('script'); cs.src = me.replace(/theme\.js(\?.*)?$/, 'copyright.js'); document.head.appendChild(cs); }

  // vineyard-in-fog watermark (assets/vineyard_watermark.css) on the Infos pages below — 2026-10-19 (user)
  var WATERMARK_PAGES = ['/French_Wine_in_Numbers.html', '/Cepages_et_Appellations.html', '/Vintage_Chart.html',
    '/Crus_Classifications.html', '/Vine_Plant.html', '/Vine_Cycle.html', '/Vine_Terroir.html', '/Vine_Planting.html',
    '/Vine_Pruning.html', '/Vine_Canopy.html', '/Vine_Threats.html', '/Vine_Farming.html', '/Vine_Harvest.html',
    '/Vine_Glossary.html', '/Wine_Label.html', '/Wine_Tasting.html', '/History_of_Wine.html', '/Wine_Quotes.html',
    '/Jeux.html', '/Wine_Quiz.html', '/Taste_Quiz.html', '/Map_Game.html', '/Bon_Cep.html', '/IGP_Game.html',
    '/wine_chemistry_web.html', '/wine_compound_count_web.html', '/How brandy is made.html', '/How wine is made.html',
    '/How wine is made - Illustrated.html', '/How sparkling wine is made.html', '/Bottle_Sizes.html', '/Barrel_Making.html', '/Geology_Map.html'];
  var here = '';
  try { here = decodeURIComponent(location.pathname); } catch (e) { here = location.pathname; }
  if (me && WATERMARK_PAGES.some(function (p) { return here.slice(-p.length) === p; })) {
    var wm = document.createElement('link'); wm.rel = 'stylesheet';
    wm.href = me.replace(/theme\.js(\?.*)?$/, 'vineyard_watermark.css?v=1'); document.head.appendChild(wm);
  }

  // source pop-ups on superscript references (assets/ref_tips.js)
  if (me) { var rs = document.createElement('script'); rs.src = me.replace(/theme\.js(\?.*)?$/, 'ref_tips.js'); document.head.appendChild(rs); }
})();
